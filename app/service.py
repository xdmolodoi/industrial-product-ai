import json
import os
import re
from pydantic import ValidationError

from .prompts import SYSTEM_PROMPT, build_user_prompt
from .schemas import ProductCard, ProductInput


class GenerationError(Exception):
    pass


def _source_values(product: ProductInput) -> set[str]:
    """Collect source strings used by the conservative numeric-token check."""
    values = [product.name, product.manufacturer or "", product.description or ""]
    values.extend(str(v) for v in product.specs.values())
    return set(values)


def _check_technical_tokens(card: ProductCard, product: ProductInput) -> None:
    """Reject numeric/measurement tokens in generated copy unless present in source.

    This is a safety net, not a complete factuality proof. Structured characteristics
    are also rebuilt from the input so the model cannot alter their values.
    """
    source = " ".join(_source_values(product))
    generated = " ".join([
        card.seo_title, card.seo_description, card.commercial_block,
        *card.search_queries, *card.key_characteristics.values()
    ])
    tokens = re.findall(r"(?<!\w)\d+(?:[.,]\d+)?(?:\s?(?:мм|см|м|кПа|МПа|Па|бар|В|А|мА|°C|%))?", generated, re.I)
    for token in tokens:
        normalized = re.sub(r"\s+", "", token).replace(",", ".")
        source_normalized = re.sub(r"\s+", "", source).replace(",", ".")
        if normalized not in source_normalized:
            raise GenerationError(f"Модель добавила неподтверждённое числовое значение: {token}")


def generate_card(product_data: ProductInput) -> ProductCard:
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        raise GenerationError("Не задан OPENAI_API_KEY. Скопируйте .env.example в .env и добавьте ключ.")

    try:
        from openai import OpenAI
    except ImportError as exc:
        raise GenerationError("Не установлен пакет openai. Выполните pip install -r requirements.txt") from exc

    client = OpenAI(api_key=api_key, timeout=45.0, max_retries=1)
    model = os.getenv("OPENAI_MODEL", "gpt-4o-mini")
    try:
        response = client.chat.completions.create(
            model=model,
            temperature=0.2,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": build_user_prompt(product_data.model_dump())},
            ],
        )
        content = response.choices[0].message.content
        if not content:
            raise GenerationError("LLM вернула пустой ответ")
        raw = json.loads(content)
        card = ProductCard.model_validate(raw)
    except GenerationError:
        raise
    except json.JSONDecodeError as exc:
        raise GenerationError("LLM вернула некорректный JSON") from exc
    except ValidationError as exc:
        raise GenerationError(f"Ответ LLM не соответствует схеме: {exc}") from exc
    except Exception as exc:
        raise GenerationError(f"Ошибка обращения к LLM API: {exc.__class__.__name__}: {exc}") from exc

    if len(card.seo_title) > 70:
        raise GenerationError(f"SEO-заголовок длиннее 70 символов ({len(card.seo_title)})")
    description_length = len(card.seo_description)
    if not 800 <= description_length <= 1200:
        raise GenerationError(f"SEO-описание должно быть 800–1200 символов; получено {description_length}")

    # Canonical characteristics are always copied from source, never generated by the LLM.
    canonical_specs = {str(k): str(v) if v not in (None, "") else "данных нет"
                       for k, v in product_data.specs.items()}
    for key, value in card.key_characteristics.items():
        if key not in canonical_specs:
            canonical_specs[key] = "данных нет"
    card.key_characteristics = canonical_specs

    _check_technical_tokens(card, product_data)
    return card
